"""
update-learning-pages.py - checks new proof and rebuilds the user's progress pages

WHAT THIS FILE IS
A Python script. Python is a programming language; the program "python3" runs
this file from top to bottom. Text between three quote marks and lines that
start with "#" are explanations for people; Python skips them.

WHY IT EXISTS
The tutor records proof as lines of JSON in one file,
.claude/learning/progress/proof-log.jsonl (the template for one line, with
the explanation: .claude/learning/progress/proof-log.jsonl.explained.md). The user reads easy
pages instead, which this script writes:
    .claude/learning/progress/overview.md     the overall percentage, one bar per
                                              subject, what to learn next, what
                                              to review
    .claude/learning/progress/<subject>.md    per subject: a bar per branch, the
                                              user's own words under each concept
                                              they proved, what is ready next, and
                                              how many concepts are still locked
Checking proof and turning it into pages needs no thinking, so a script does
it, always the same way, the moment the proof changes. No language model is
involved. The statuses are calculated by .claude/hooks/shared/learning_state.py.

WHO RUNS IT, AND WHEN
Claude Code runs it through hooks in .claude/settings.json:
- "PostToolUse" with the matcher Write|Edit: right after any agent writes or
  changes a file. Claude Code sends the file's path as JSON on standard input.
  The script works only when the file is inside .claude/learning/ (the proof
  log, the skill tree or the profile).
- "SessionStart": at the start of every session, so "time to review" fits the
  new day even when nothing was written yet.
It can also be run by hand:
    python3 .claude/hooks/after-file-change/update-learning-pages.py
A page is rewritten only when its content changed.

INSTANT FEEDBACK
When the tutor has just written the proof log and an entry does not count (an
unknown concept, a missing quote, a quote not found in the user's messages),
the script ends with "exit code 2" and lists the problems. For the PostToolUse
moment, this shows the list to the tutor at once, so it fixes the entry in the
same answer. The pages are still rebuilt first.

WORKS WITH
  .claude/hooks/shared/learning_state.py   - calculates the statuses
  .claude/templates/proof-entry.md         - the template for one proof entry
"""

import glob      # finds files by a name pattern
import json      # reads JSON text
import os        # works with files and folders
import sys       # standard input, standard error and the exit code
from datetime import date

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "shared"))
import learning_state as ls

# Read the input only when Claude Code sends some; run by hand, there is none.
data = {}
if not sys.stdin.isatty():
    raw = sys.stdin.buffer.read().decode("utf-8")
    data = json.loads(raw) if raw.strip() else {}

project = os.environ.get("CLAUDE_PROJECT_DIR") or data.get("cwd") or "."


# After a file change, work only when the changed file is learning data.
changed = (data.get("tool_input") or {}).get("file_path", "")
proof_changed = False
if changed:
    path = os.path.normcase(os.path.abspath(changed))
    if not path.startswith(os.path.normcase(os.path.abspath(os.path.join(project, ls.LEARNING)))):
        sys.exit(0)  # not learning data: nothing to rebuild
    proof_changed = path == os.path.normcase(os.path.abspath(os.path.join(project, ls.PROOF_LOG)))
# (The pages are written below with Python, not with Claude's file tools, so
# writing them never starts this hook again.)

subjects, concepts, state, problems = ls.compute(project, data.get("transcript_path"))
folder = os.path.join(project, ls.PROGRESS)
os.makedirs(folder, exist_ok=True)

# Plain words for each kind of entry, as the user reads them.
KIND_WORDS = {"did": "you did it", "partial": "you explained part of it",
              "explained": "you explained it", "answered": "you answered a check",
              "missed": "you missed a check"}
GENERATED = "<!-- Generated by .claude/hooks/after-file-change/update-learning-pages.py. Do not edit by hand. -->"


def bar(ids):
    """A bar of 10 blocks and the percentage, such as "▰▰▱▱▱▱▱▱▱▱ 20%"."""
    p = ls.percent(state, ids)
    full = round(p / 10)
    return "▰" * full + "▱" * (10 - full) + f" {p}%"


def day(d):
    """A date as "5 Oct"."""
    d = d if isinstance(d, date) else date.fromisoformat(d[:10])
    return f"{d.day} {d:%b}"


def totals(ids):
    c = ls.counts(state, ids)
    return f"{c['learned']} learned, {c['in progress']} in progress, {c['not started']} not started"


def where(cid):
    return f"{concepts[cid]['subject']}, {concepts[cid]['branch']}"


pages = {}  # file name -> list of lines

# ---- overview.md -------------------------------------------------------------
everything = list(concepts)
name = ls.user_name(project)
out = [f"# {name}'s learning" if name else "# Your learning", "", GENERATED, "",
       f"**Overall: {bar(everything)}**", "", f"{totals(everything)}, of {len(everything)} concepts.", "",
       "| Subject | Proved |", "|---|---|"]
for subject in subjects:
    ids = [cid for b in subject["branches"] for cid in b["ids"]]
    out.append(f"| [{subject['name']}]({subject['file']}) | {bar(ids)} |")

out += ["", "## Next to learn", ""]
out += [f"{i}. **{concepts[cid]['name']}** ({where(cid)}): {concepts[cid]['what']}"
        for i, cid in enumerate(ls.ready_next(subjects, concepts, state, 3), 1)] or ["Nothing is ready yet."]

due = ls.due_for_review(concepts, state, 3)
if due:
    out += ["", "## Time to review", ""]
    out += [f"{i}. **{concepts[cid]['name']}** ({where(cid)}), {state[cid]['status']}, "
            f"last proof {day(state[cid]['last'])}" for i, cid in enumerate(due, 1)]

out += ["", "## How to read these pages", "",
        "- **Learned**: you explained it fully in your own words, or answered a check correctly.",
        "- **In progress**: you did it yourself, or explained part of it.",
        "- **Not started**: there is no proof from you yet, even if the tutor already talked about it.",
        "- **Ready next**: everything it needs already has your proof, so you can learn it now.",
        "- **Locked**: it needs something you have not proved yet.",
        "- The percentage counts 1 point for in progress and 2 for learned, out of 2 per concept.",
        "- Every proof is a quote of your own words, checked word for word against your messages."]

if problems:
    out += ["", "## Needs fixing", "", "These entries did not count. The tutor corrects these lines.", ""]
    out += [f"- {p}" for p in problems]
pages["overview.md"] = out

# ---- one page per subject ----------------------------------------------------
for subject in subjects:
    ids = [cid for b in subject["branches"] for cid in b["ids"]]
    out = [f"# {subject['name']}", "", GENERATED, "",
           f"**{bar(ids)}**", "", f"{totals(ids)}. Back to the [overview](overview.md).", ""]
    for branch in subject["branches"]:
        out += [f"## {branch['name']}  {bar(branch['ids'])}", ""]
        proved = [cid for cid in branch["ids"] if state[cid]["status"] != "not started"]
        for cid in proved:
            status = state[cid]["status"]
            out.append(f"- **{concepts[cid]['name']}**: {status}")
            # Only the entries that decide the status (and missed checks), the
            # newest first, at most 2, so the page stays short.
            level = ls.STATUSES.index(status)
            deciding = [e for e in reversed(state[cid]["entries"])
                        if e["kind"] == "missed" or ls.KIND_LEVEL.get(e["kind"]) == level]
            for e in deciding[:2]:
                out.append(f"  - {day(e['timestamp'])}, {KIND_WORDS[e['kind']]}: \"{e['quote']}\"")
        if proved:
            out.append("")
        ready = [concepts[cid]["name"] for cid in branch["ids"] if ls.is_ready(cid, concepts, state)]
        locked = sum(1 for cid in branch["ids"] if state[cid]["status"] == "not started"
                     and not ls.is_ready(cid, concepts, state))
        if ready:
            more = f", and {len(ready) - 3} more" if len(ready) > 3 else ""
            out.append(f"Ready next: {', '.join(ready[:3])}{more}.  ")
        if locked:
            out.append(f"Locked for now: {locked}.")
        out.append("")
    pages[subject["file"]] = out

# ---- write the pages, and remove pages of subjects that no longer exist ------
for file_name, lines in pages.items():
    text = "\n".join(lines).rstrip() + "\n"
    page = os.path.join(folder, file_name)
    if ls.read(page) != text:
        with open(page, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
# Only a page this script made (it carries the GENERATED mark) is ever removed;
# other files in the folder, such as the explanation of the proof log or
# copied messages, are never touched.
for page in glob.glob(os.path.join(folder, "*.md")):
    if os.path.basename(page) not in pages and GENERATED in ls.read(page):
        os.remove(page)

# ---- instant feedback to the tutor -------------------------------------------
if proof_changed and problems:
    message = ("Some proof entries do not count. Correct each of these lines "
               "(the rule for correcting a line: .claude/learning/progress/proof-log.jsonl.explained.md):\n" + "\n".join(f"- {p}" for p in problems) + "\n")
    sys.stderr.buffer.write(message.encode("utf-8"))
    sys.exit(2)
